#!/usr/bin/env node
// Builds the Material 3 profile: assets/{light,dark}/*.svg (+ README.md on first run).
//   node scripts/generate.mjs            fetch live stats, render everything
//   node scripts/generate.mjs --offline  reuse data/stats.json (no network)
//   node scripts/generate.mjs --readme   also rewrite README.md from the config
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { makeTheme } from './lib/theme.mjs';
import { loadStats } from './lib/github.mjs';
import { CARDS, button, fill, vars } from './cards.mjs';

const ROOT = new URL('../', import.meta.url);
const args = new Set(process.argv.slice(2));
const cfg = JSON.parse(readFileSync(new URL('profile.config.json', ROOT), 'utf8'));

function clock(timeZone) {
  const d = new Date();
  const fmt = (locale, o) => new Intl.DateTimeFormat(locale, { timeZone, ...o });
  return {
    date: fmt('en-US', { weekday: 'short', month: 'short', day: 'numeric' }).format(d), // Mon, Nov 16
    long: fmt('en-GB', { day: 'numeric', month: 'short' }).format(d), // 16 Nov
    time: fmt('en-GB', { hour: '2-digit', minute: '2-digit', hour12: false }).format(d), // 00:08
    zone: fmt('en-GB', { timeZoneName: 'short' }).formatToParts(d).find((p) => p.type === 'timeZoneName')?.value || '',
  };
}

function write(rel, content) {
  const url = new URL(rel, ROOT);
  mkdirSync(new URL('./', url), { recursive: true });
  writeFileSync(url, content);
  console.log(`  ${rel.padEnd(34)} ${(Buffer.byteLength(content) / 1024).toFixed(1)} KB`);
}

const stats = await loadStats(cfg, { offline: args.has('--offline') });
const now = clock(cfg.timezone || 'UTC');

for (const mode of ['light', 'dark']) {
  const ctx = { t: makeTheme(cfg.theme, mode === 'dark'), cfg, stats, now };
  for (const [name, render] of Object.entries(CARDS)) write(`assets/${mode}/${name}.svg`, render(ctx));
  for (const b of cfg.buttons || []) write(`assets/${mode}/btn-${b.id}.svg`, button(ctx, b));
}

// README: only written on first run or with --readme, so hand edits survive the daily refresh.
const README = new URL('README.md', ROOT);
if (args.has('--readme') || !existsSync(README)) {
  const v = vars(cfg, stats);
  const pic = (name, alt, attrs = 'width="100%"') => `<picture>
  <source media="(prefers-color-scheme: dark)" srcset="assets/dark/${name}.svg">
  <img alt="${alt.replace(/"/g, '&quot;')}" src="assets/light/${name}.svg" ${attrs}>
</picture>`;
  const featuredUrl = stats.featured?.url || `https://github.com/${cfg.username}`;
  const buttons = (cfg.buttons || []).map((b) => `<a href="${fill(b.href, v)}">${pic(`btn-${b.id}`, fill(b.label, v), 'height="56"')}</a>`).join('\n&nbsp;\n');
  const md = `<!-- Generated by scripts/generate.mjs: edit profile.config.json, then run \`npm run build -- --readme\`. -->
<div align="center">

${pic('hero', `${v.name}: ${fill(cfg.tagline || '', v)}`)}

${pic('quick-settings', 'Quick settings: what I am into right now')}

<a href="${featuredUrl}">
${pic('now-playing', `Featured project: ${cfg.featured?.title || stats.featured?.name || ''}`)}
</a>

${pic('stats', 'Public repos, stars earned, followers and contributions')}

${pic('activity', 'Contributions in the last 7 days and top languages')}

${pic('toolbox', `Toolbox: ${(cfg.toolbox?.chips || []).map((c) => c.label).join(', ')}`)}

${buttons}

${pic('footer', 'Last updated')}

</div>
`;
  write('README.md', md);
}
console.log(`Done. ${stats.login}: ${stats.publicRepos} repos, ${stats.stars} stars, ${stats.contributions?.total ?? '?'} contributions.`);
